/**
 * Phonetic transliterator fallback for any English/Latin words not in the dictionary
 */
export function transliterateWordPhonetic(rawWord: string): string {
  if (!rawWord || !/[a-zA-Z]/.test(rawWord)) return rawWord;

  const w = rawWord.toLowerCase();

  const digraphs: [string, string][] = [
    ["shh", "શ"],
    ["chh", "છ"],
    ["sh", "શ"],
    ["ch", "ચ"],
    ["kh", "ખ"],
    ["gh", "ઘ"],
    ["th", "થ"],
    ["dh", "ધ"],
    ["bh", "ભ"],
    ["ph", "ફ"],
    ["jh", "ઝ"],
    ["zh", "ઝ"],
    ["gn", "જ્ઞ"],
    ["tr", "ત્ર"],
    ["ee", "ી"],
    ["oo", "ૂ"],
    ["ai", "ૈ"],
    ["au", "ૌ"],
    ["ay", "ય"]
  ];

  const singleLetters: Record<string, string> = {
    k: "ક", g: "ગ", c: "ક", j: "જ", z: "ઝ",
    t: "ટ", d: "ડ", n: "ન", p: "પ", f: "ફ",
    b: "બ", m: "મ", y: "ય", r: "ર", l: "લ",
    v: "વ", w: "વ", s: "સ", h: "હ", x: "ક્ષ",
    a: "ા", i: "િ", u: "ુ", e: "ે", o: "ો"
  };

  let out = "";
  let i = 0;
  while (i < w.length) {
    let matched = false;
    for (const [dg, rep] of digraphs) {
      if (w.startsWith(dg, i)) {
        out += rep;
        i += dg.length;
        matched = true;
        break;
      }
    }
    if (!matched) {
      const ch = w[i];
      if (singleLetters[ch]) {
        if (i === 0) {
          if (ch === "a") out += "આ";
          else if (ch === "i") out += "ઇ";
          else if (ch === "u") out += "ઉ";
          else if (ch === "e") out += "એ";
          else if (ch === "o") out += "ઓ";
          else out += singleLetters[ch];
        } else {
          out += singleLetters[ch];
        }
      } else {
        out += ch;
      }
      i++;
    }
  }
  return out;
}

/**
 * Transliterates Gujlish words, converts English digits, and replaces any Latin characters with Gujarati script
 */
export function transliterateGujlishSentence(sentence: string): string {
  if (!sentence) return sentence;

  // If sentence has no Latin characters or digits to convert, return as is
  if (!/[a-zA-Z0-9]/.test(sentence)) {
    return sentence;
  }

  // Tokenize preserving spaces, punctuation, symbols
  const tokens = sentence.split(/(\s+|[.,;:\/()\-]+)/);

  const translated = tokens.map((tok) => {
    // Preserve spaces & punctuation
    if (/^(\s+|[.,;:\/()\-]+)$/.test(tok)) {
      return tok;
    }

    const clean = tok.toLowerCase().trim();
    if (!clean) return tok;

    // 1. Direct match in dictionary
    if (gujlishWords[clean]) {
      return gujlishWords[clean];
    }

    // 2. Pure numbers: convert to Gujarati numerals
    if (/^\d+$/.test(clean)) {
      return clean.replace(/\d/g, (d) => "૦૧૨૩૪૫૬૭૮૯"[parseInt(d, 10)]);
    }

    // 3. If word contains Latin letters, fall back to phonetic transliteration
    if (/[a-zA-Z]/.test(clean)) {
      return transliterateWordPhonetic(clean);
    }

    return tok;
  }).join("");

  return translated;
}

